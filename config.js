/* =========================================================
   Режим проведения вебинара (feature flag).

   Это статический сайт (GitHub Pages), поэтому флаг задаётся
   ПРЯМО В КОДЕ и вступает в силу после коммита и деплоя (push).
   Отдельной настройки при деплое нет: меняете mode здесь → пушите.

   mode: 'streams' — несколько потоков (обычно подряд несколько дней).
                     Сайт работает как раньше: выпадающий список дат,
                     занятость мест и лист ожидания берутся из slots.js.

   mode: 'single'  — один вебинар в конкретную дату и время.
                     В форме вместо списка показывается красивая дата,
                     а по сайту скрываются упоминания «выберите поток».
                     Правьте блок single ниже.

   После правки обновите страницу с очисткой кеша: Ctrl+F5 (Cmd+Shift+R).
   ========================================================= */
window.WEBINAR_CONFIG = {
  mode: 'single',

  // Используется только в режиме 'single'
  single: {
    // Уходит в заявку (Formspree). Формат менять без необходимости не нужно.
    value: '10 сентября, 20:00',
    // Как дата и время показываются в форме (красиво)
    dateText: 'Четверг, 10 сентября',
    timeText: '20:00 по Канкуну (GMT-5)',
    // Верхняя промо-полоса
    promoText: '10 сентября · онлайн · 230 песо'
  }
};
